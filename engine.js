function evalMcmaster(applicant) {
  const { cgpa } = processGpa(applicant);
  const cars = applicant.mcat_sections.cars;
  const casper = applicant.casper_percentile;

  // Access the graduate degree string from the applicant object.
  // (Change "graduate_degree" to the exact property name used in your data structure)
  const degree = applicant.graduate_degree || "none";

  const required = mcmasterRequiredCasper(cgpa, cars, degree);
  const result = checkInterviewInvite(cgpa, cars, casper, degree);

  if (result === "Yes") return {
    status: "Likely competitive",
    type: "competitive",
    explanation: `McMaster's formula uses your cGPA (${cgpa.toFixed(2)}), CARS (${cars}), and CASPer (mapped percentile ${casper}) together. With CARS ${cars}, the model requires roughly ${required} CASPer equivalent; your score meets or exceeds that, so the formula output is favourable. This result is based solely on the published GPA–CARS–CASPer interaction, not holistic file review.`
  };

  return {
    status: "Likely not eligible",
    type: "not-eligible",
    explanation: `McMaster's formula uses your cGPA (${cgpa.toFixed(2)}), CARS (${cars}), and CASPer (mapped percentile ${casper}) together. With CARS ${cars}, the model requires roughly ${required} CASPer equivalent; your score is below that threshold, so the formula output is unfavourable.`
  };
}

function adjustedUBCGpa(applicant) {
  const years = applicant.gpa_by_year;
  if (years && years.length >= 4) {
    // drop the lowest year and average the rest
    const sorted = [...years].sort((a, b) => a - b);
    const dropped = sorted.slice(1); // drop lowest
    const avg = dropped.reduce((sum, val) => sum + val, 0) / dropped.length;
    return avg;
  }
  return applicant.cgpa;
}

function evalUBC(applicant) {
  const gpa = adjustedUBCGpa(applicant);
  const mcatSum = Object.values(applicant.mcat_sections).reduce((a, b) => a + b, 0);

  const gpaOk = gpa >= 3.85;
  const mcatOk = mcatSum >= 505;

  let explanation = `The official UBC cutoffs are 75% for BC residents and 85% for out-of-province applicants, but realistically a minimum GPA of 87% or 3.85 is needed for a realistic chance. The official MCAT minimum is 496 but 505 or more is recommended.`;

  if (gpaOk && mcatOk) {
    explanation += ` While your academic stats are within range, your non-academic quality (NAQ) section will be very important in your ability to get an interview.`;
  }

  if (gpaOk && mcatOk) {
    return {
      status: "Likely eligible",
      type: "eligible",
      explanation
    };
  }

  return {
    status: "Likely not eligible",
    type: "not-eligible",
    explanation
  };
}

function evalUCalgary(applicant) {
  const { cgpa, province, mcat_sections } = applicant;
  const provinceLow = province ? province.trim().toLowerCase() === "alberta" : false;

  // Cutoffs based on province
  const minGpa = provinceLow ? 3.7 : 3.88;
  const minCars = provinceLow ? 126 : 128;
  const carsScore = mcat_sections.cars;

  const gpaOk = cgpa >= minGpa;
  const carsOk = carsScore >= minCars;

  let regionalNote = `UCalgary reserves roughly 85% of its seats for Alberta residents.`;
  let type = 'not-eligible';
  let status = 'Likely not eligible';

  if (gpaOk && carsOk) {
    status = 'Likely eligible';
    type = 'eligible';
  }

  const minMsg = provinceLow
    ? `The minimum GPA and CARS scores required for a realistic chance at UCalgary for in-province applicants are ${minGpa.toFixed(2)} and ${minCars}, respectively, which are higher than the officially reported cutoffs.`
    : `The minimum GPA and CARS scores required for a realistic chance at UCalgary for out-of-province applicants are ${minGpa.toFixed(2)} and ${minCars}, respectively, which are higher than the officially reported cutoffs.`;

  let explanation = minMsg + ' ';

  if (!gpaOk || !carsOk) {
    const reasons = [];
    if (!gpaOk) reasons.push(`cGPA ${cgpa.toFixed(2)} is below ${minGpa.toFixed(2)}`);
    if (!carsOk) reasons.push(`CARS ${carsScore} is below ${minCars}`);
    explanation += reasons.join('; ') + '. ';
  }

  explanation += regionalNote;

  return { status, type, explanation };
}



function evalMcGill(applicant) {
  const { cgpa, province, casper_percentile } = applicant;
  const isQuebec = province.trim().toLowerCase() === "quebec";
  const minGpa = isQuebec ? 3.7 : 3.9;
  const minCasper = isQuebec ? 38 : 63;

  const gpaOk = cgpa >= minGpa;
  const casperOk = casper_percentile >= minCasper;

  if (gpaOk && casperOk) {
    return {
      status: "Likely eligible",
      type: "eligible",
      explanation: `You meet McGill's requirements as an applicant from ${province} with a minimum cGPA of ${minGpa.toFixed(1)} and CASPer in the required quartile or higher.`
    };
  }

  let failReasons = [];
  if (!gpaOk) failReasons.push(`cGPA ${cgpa.toFixed(2)} is below the minimum required ${minGpa.toFixed(1)}`);
  if (!casperOk) failReasons.push(`CASPer equivalent ${casper_percentile} is below required quartile cutoff`);

  return {
    status: "Likely not eligible",
    type: "not-eligible",
    explanation: `You do not meet McGill's requirements because ${failReasons.join("; ")}.`
  };
}


