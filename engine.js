const MCAT_KEYS = ["cp", "cars", "bb", "ps"];
const MCAT_LABELS = { cp: "CP", cars: "CARS", bb: "BB", ps: "PS" };

const CASPER_QUARTILE_MAP = { Q1: 13, Q2: 38, Q3: 63, Q4: 88 };

// ── GPA utilities ──

function processGpa(applicant) {
  const cgpa = applicant.cgpa;
  const years = applicant.gpa_by_year;
  if (years && years.length > 0) {
    const sorted = [...years].sort((a, b) => b - a);
    const best2 = sorted.slice(0, 2).reduce((s, v) => s + v, 0) / Math.min(2, sorted.length);
    const recent = years.slice(-3);
    const last3 = recent.reduce((s, v) => s + v, 0) / recent.length;
    return { cgpa, best2, last3 };
  }
  return { cgpa, best2: cgpa, last3: cgpa };
}

function westernBestTwoYears(applicant) {
  const years = applicant.gpa_by_year;
  if (years && years.length > 0) return [...years].sort((a, b) => b - a).slice(0, 2);
  return [applicant.cgpa];
}

function westernGpaEligible(applicant) {
  return westernBestTwoYears(applicant).every(y => y >= 3.70);
}

// ── MCAT utilities ──

function mcatValues(applicant) {
  return MCAT_KEYS.map(k => applicant.mcat_sections[k]);
}

function uoftMcatEligible(applicant) {
  const vals = mcatValues(applicant);
  if (vals.every(s => s >= 125)) return true;
  const below = vals.filter(s => s < 125);
  return below.length === 1 && below[0] >= 124;
}

function uoftMcatFailures(applicant) {
  const sections = applicant.mcat_sections;
  const below125 = MCAT_KEYS.filter(k => sections[k] < 125);
  return MCAT_KEYS.reduce((arr, key) => {
    const score = sections[key];
    if (score < 124) {
      arr.push(`${MCAT_LABELS[key]} (${score})`);
    } else if (score === 124 && below125.length > 1) {
      arr.push(`${MCAT_LABELS[key]} (${score})`);
    }
    return arr;
  }, []);
}

// ── McMaster formula ──

const CARS_BASELINE = { 132: 40, 131: 51, 130: 62, 129: 77, 128: 85, 127: 91, 126: 96, 125: 100 };

// Helper to determine the CASPer percentile reduction based on the degree
function getDegreeOffset(degree) {
  if (!degree) return 0;

  const normalized = degree.toLowerCase().trim();
  if (normalized === "course" || normalized === "thesis") {
    return 3.125; // 1% overall bonus converts to ~3.125 CASPer percentile points
  } else if (normalized === "phd") {
    return 12.5;   // 4% overall bonus converts to 12.5 CASPer percentile points
  }
  return 0; // "none" or any other unrecognized value
}

function mcmasterRequiredCasper(gpa, cars, degree = "none") {
  const clampedGpa = Math.max(0, Math.min(4.0, gpa));
  const base = CARS_BASELINE[cars] ?? 100;
  const offset = getDegreeOffset(degree);

  // Adjusted required CASPer is floored at 0 and capped at 100
  return Math.round(Math.max(0, Math.min(100, base + 50 * (4.0 - clampedGpa) - offset)));
}

function checkInterviewInvite(gpa, cars, casperPercentile, degree = "none") {
  const clampedGpa = Math.max(0, Math.min(4.0, gpa));
  const clampedCasper = Math.max(0, Math.min(100, casperPercentile));
  const base = CARS_BASELINE[cars] ?? 100;
  const offset = getDegreeOffset(degree);

  const required = Math.max(0, Math.min(100, base + 50 * (4.0 - clampedGpa) - offset));
  return clampedCasper >= required ? "Yes" : "No";
}

// ── School evaluators ──

function evalUoft(applicant) {
  const { cgpa, graduate_degree } = applicant;

  // Determine minimum GPA based on graduate degree
  let minGpa = 3.85;
  let gradNote = "";

  if (graduate_degree === "thesis") {
    minGpa = 3.75;
    gradNote = ". Since you have a thesis-based Master's, the minimum GPA requirement is around 3.75";
  } else if (graduate_degree === "phd") {
    minGpa = 3.65;
    gradNote = ". Since you have a PhD, the minimum GPA requirement is around 3.65";
  }

  const gpaOk = cgpa >= minGpa;
  const mcatOk = uoftMcatEligible(applicant);

  if (gpaOk && mcatOk) return {
    status: "Likely eligible",
    type: "eligible",
    explanation: `Your cGPA of ${cgpa.toFixed(2)} and MCAT profile meet UofT's academic screening thresholds${gradNote}, so you are academically competitive at this stage. This means you have your foot in the door for further review, not a guaranteed interview. UofT's final decisions depend heavily on your autobiographical sketch (ABS) and essays, where non-academic strengths and fit are weighed after the initial screen.`
  };

  const reasons = [];
  if (!gpaOk) reasons.push(`cGPA ${cgpa.toFixed(2)} is below ${minGpa.toFixed(2)}, which is sometimes quoted as the minimum GPA possible for an interview (3.89 is another number sometimes quoted)`);
  if (!mcatOk) {
    const failed = uoftMcatFailures(applicant);
    if (failed.length) reasons.push("MCAT section(s) below threshold: " + failed.join(", "));
    else reasons.push("MCAT does not meet the rule (all sections 65 125, with at most one at 124)");
  }
  return {
    status: "Likely not eligible",
    type: "not-eligible",
    explanation: `You do not meet UofT's academic screen based on the following: ${reasons.join("; ")}. Without being in the competitive GPA range or meeting the MCAT cutoffs, your file is unlikely to advance regardless of ABS or essays. Strengthen the listed area(s) before reapplying or targeting UofT.${gradNote}`
  };
}

